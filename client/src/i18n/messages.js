export const MESSAGES = { vi, en, fr, ja, ko, "zh-CN": zhCN };

export function isSupportedLang(code) {
  return LANGUAGES.some((l) => l.code === code);
}

// Ngôn ngữ trình duyệt -> ngôn ngữ của web ("en-US" -> "en", "zh-Hans-CN" / "zh" -> "zh-CN")
export function matchBrowserLang(browserLangs = []) {
  for (const raw of browserLangs) {
    const code = String(raw).toLowerCase();
    if (code.startsWith("zh")) return "zh-CN";
    const base = code.split("-")[0];
    const found = LANGUAGES.find((l) => l.code === base);
    if (found) return found.code;
  }
  return DEFAULT_LANG;
}

// Lấy chuỗi theo key, thay {tên} bằng giá trị. Thiếu thì dùng tiếng Việt, thiếu nữa thì trả lại key.
export function translate(lang, key, vars) {
  const text = MESSAGES[lang]?.[key] ?? vi[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}
